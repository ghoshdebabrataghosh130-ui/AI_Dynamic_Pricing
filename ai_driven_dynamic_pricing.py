#Creating a dynamic pricing engine
def dynamic_price_engine(predicted_price, inventory, demand, min_price, max_price):
  recommended_price = predicted_price
  reason = "Base ML Prediction"

  #High Demand
  if demand == "high" and inventory == "low":
    recommended_price *= 1.10
    reason = "High Demand, Low Inventory"
  elif demand == "high" and inventory == "normal":
    recommended_price *= 1.05
    reason = "High Demand, Normal Inventory"
  elif demand == "high" and inventory == "high":
    recommended_price *= 1.02
    reason = "High Demand, High Inventory"

  #Low Demand
  elif demand == "low" and inventory == "high":
    recommended_price *= 0.90
    reason = "Low Demand, High Inventory"
  elif demand == "low" and inventory == "normal":
    recommended_price *= 0.95
    reason = "Low Demand, Normal Inventory"
  elif demand == "low" and inventory == "low":
    recommended_price *= 0.98
    reason = "Low Demand, Low Inventory"

  #Normal Demand
  elif demand == "normal" and inventory == "high":
    recommended_price *= 1.05
    reason = "Normal Demand, High Inventory"
  elif demand == "normal" and inventory == "low":
    recommended_price *= 0.95
    reason = "Normal Demand, Low Inventory"
  elif demand == "normal" and inventory == "normal":
    recommended_price *= 1.00
    reason = "Normal Demand, Normal Inventory"

  #Applying maximum and minimum business constraints
  recommended_price = max(min_price, recommended_price)
  recommended_price = min(max_price, recommended_price)

  return {"predicted price": round(predicted_price,2),
          "actual price": round(recommended_price, 2),
          "reason" : reason}

